function tentukanUmpanBalik(persentase) {
    if (persentase < 55) {
        return "Kurang";
    } else if (persentase >= 55 && persentase <= 69) {
        return "Cukup";
    } else if (persentase >= 70 && persentase <= 84) {
        return "Baik";
    } else if (persentase >= 85 && persentase <= 100) {
        return "Sangat Baik";
    }
    return "-"; // Fallback
}

function updatePencapaianAtlet() {
    // 1. Ambil data riwayat terbaru dari localStorage
    const rawRiwayat = localStorage.getItem('petanqueRiwayat');
    const listRiwayat = rawRiwayat ? JSON.parse(rawRiwayat) : [];

    // 2. Jika belum ada riwayat, pencapaian tetap 0
    if (listRiwayat.length === 0) {
        dataAtlet.pencapaian_atlet = 0;
    } else {
        // 3. Hitung total persentase dari semua sesi
        const totalPersen = listRiwayat.reduce((sum, item) => sum + item.persentase, 0);
        
        // 4. Hitung rata-rata dan bulatkan (misal 1 angka di belakang koma)
        const rataRata = (totalPersen / listRiwayat.length).toFixed(1);
        
        dataAtlet.pencapaian_atlet = parseFloat(rataRata);
    }

    // 5. Simpan dataAtlet yang telah diperbarui ke localStorage
    localStorage.setItem('petanqueAtlet', JSON.stringify(dataAtlet));

    // 6. Update tampilan di dashboard jika diperlukan
    updateUIProfil();
}

function simpanSesiLatihan(dataBaru) {
    // Ambil riwayat lama
    let listRiwayat = JSON.parse(localStorage.getItem('petanqueRiwayat') || "[]");
    
    // Tambah data baru ke atas
    listRiwayat.unshift(dataBaru);
    
    // Simpan riwayat kembali
    localStorage.setItem('petanqueRiwayat', JSON.stringify(listRiwayat));

    // OTOMATIS Update Pencapaian di Profil
    updatePencapaianAtlet();
    
    toast("Latihan berhasil disimpan dan pencapaian diperbarui!");
}

